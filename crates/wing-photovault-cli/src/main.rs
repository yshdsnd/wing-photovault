struct ScanOpts<'a> {
    storage_filter: Option<&'a str>,
    full: bool,
    export_jsonl: bool,
    cooldown_every: usize,
    cooldown_secs: u64,
    max_files: Option<usize>,
    quiet: bool,
    format: OutputFormat,
}

fn cmd_scan(config_path: &Path, opts: ScanOpts<'_>) -> Result<()> {
    let ScanOpts {
        storage_filter,
        full,
        export_jsonl,
        cooldown_every,
        cooldown_secs,
        max_files,
        quiet,
        format,
    } = opts;
    let cfg = Config::load(config_path)
        .with_context(|| format!("failed to load config: {}", config_path.display()))?;
    let mut db = Database::open(&cfg.general.db_path)?;
    db.upsert_host(&cfg.host.id, &cfg.host.name, current_host_os())?;
    let allowed_exts = cfg.normalized_extensions();

    let targets: Vec<&StorageConfig> = cfg
        .storages
        .iter()
        .filter(|s| storage_filter.is_none_or(|id| s.id == id))
        .collect();

    if targets.is_empty() {
        anyhow::bail!("no matching storages found in {}", config_path.display());
    }

    let mut summaries = Vec::new();
    let mode = if full || !cfg.scan.incremental {
        "full"
    } else {
        "incremental"
    };

    for storage in targets {
        if !storage.root.exists() {
            warn!(
                storage_id = %storage.id,
                root = %storage.root.display(),
                "storage root is offline/inaccessible; skipping without marking files missing"
            );
            db.upsert_storage(storage, &cfg.host.id, StorageStatus::Offline)?;
            continue;
        }

        let expected_vid = storage
            .volume_id
            .clone()
            .or_else(|| db.get_storage_volume_id(&storage.id).ok().flatten());
        match verify_volume_identity(&storage.root, expected_vid.as_deref()) {
            VolumeCheck::Matched(_) => {}
            VolumeCheck::Unconstrained { detected } => {
                if let Some(vid) = detected {
                    db.upsert_storage(storage, &cfg.host.id, StorageStatus::Online)?;
                    db.set_storage_volume_id(&storage.id, &vid)?;
                }
            }
            VolumeCheck::MissingMarker { expected } => {
                warn!(
                    storage_id = %storage.id,
                    root = %storage.root.display(),
                    expected_volume_id = %expected,
                    "volume_id marker missing on removable storage (Fail Closed); skipping without marking files missing"
                );
                db.upsert_storage(storage, &cfg.host.id, StorageStatus::Offline)?;
                continue;
            }
            VolumeCheck::Mismatch { expected, found } => {
                warn!(
                    storage_id = %storage.id,
                    root = %storage.root.display(),
                    expected_volume_id = %expected,
                    found_volume_id = %found,
                    "wrong removable volume mounted (Fail Closed); skipping without marking files missing"
                );
                db.upsert_storage(storage, &cfg.host.id, StorageStatus::Offline)?;
                continue;
            }
        }

        db.upsert_storage(storage, &cfg.host.id, StorageStatus::Online)?;
        let scan_run_id = db.start_scan_run(&storage.id, mode)?;
        let started = Instant::now();

        let existing = db.load_storage_file_index(&storage.id)?;

        let mut summary = ScanRunSummary {
            scan_run_id,
            storage_id: storage.id.clone(),
            mode: mode.to_string(),
            status: "completed".to_string(),
            ..Default::default()
        };

        let workers = cfg.performance.workers_for(storage.media);
        let cooldown_enabled = cooldown_every > 0 && cooldown_secs > 0;
        let base_batch = cfg.performance.db_batch_size.max(1);
        let batch_size = if cooldown_enabled {
            base_batch.min(cooldown_every)
        } else {
            base_batch
        };
        let role = storage.tier.default_file_role();

        // Bounded channel capacities keep peak memory O(batch_size) even for 1M+ files (32-bit safe).
        // When thermal cooldown is active, keep work queue tight so HDD I/O pauses immediately.
        let work_cap = if cooldown_enabled {
            (workers * 2).max(2)
        } else {
            batch_size.clamp(64, 1024).max(workers * 4)
        };
        let done_cap = batch_size.clamp(64, 1024).max(workers * 4);

        let scan_pb = if quiet {
            ProgressBar::hidden()
        } else {
            let pb = ProgressBar::with_draw_target(None, ProgressDrawTarget::stderr());
            pb.set_style(
                ProgressStyle::with_template(
                    "{spinner:.cyan} [{prefix}] {pos} processed ({msg}) {elapsed_precise}",
                )
                .unwrap(),
            );
            pb.set_prefix(storage.id.clone());
            pb.set_message("scanning...");
            pb.enable_steady_tick(Duration::from_millis(120));
            pb
        };

        let bytes_counter = AtomicU64::new(0);
        let discovered_counter = AtomicU64::new(0);
        let truncated_by_max_files = AtomicBool::new(false);
        let walker_done = AtomicBool::new(false);
        let in_flight = AtomicUsize::new(0);
        let gate = PauseGate::new();
        let proc_started = Instant::now();
        let meta_session = MetadataSession::new(cfg.exif.clone());

        let pipeline_result: Result<()> = thread::scope(|scope| {
            let (work_tx, work_rx) = mpsc::sync_channel::<DiscoveredFile>(work_cap);
            let (done_tx, done_rx) = mpsc::sync_channel::<PipelineMsg>(done_cap);
            let work_rx = Arc::new(Mutex::new(work_rx));

            // Stage 1: Streaming directory walker (never buffers whole catalog in a Vec)
            let done_tx_walker = done_tx.clone();
            let existing_ref = &existing;
            let allowed_exts_ref = &allowed_exts;
            let gate_ref = &gate;
            let discovered_ref = &discovered_counter;
            let truncated_ref = &truncated_by_max_files;
            let walker_done_ref = &walker_done;
            let in_flight_ref = &in_flight;

            scope.spawn(move || {
                let mut queued_for_processing: usize = 0;
                walk_storage_files(storage, allowed_exts_ref, cfg.scan.follow_symlinks, |ev| {
                    if !gate_ref.wait_if_paused() {
                        return ControlFlow::Break(());
                    }
                    match ev {
                        Err(err) => {
                            if done_tx_walker.send(PipelineMsg::DiscoveryError(err)).is_err() {
                                return ControlFlow::Break(());
                            }
                        }
                        Ok(f) => {
                            if mode == "incremental" {
                                if let Some(prev) = existing_ref.get(&f.rel_path) {
                                    if prev.byte_size == f.byte_size
                                        && prev.mtime_ns == f.mtime_ns
                                        && prev.content_id.is_some()
                                    {
                                        discovered_ref.fetch_add(1, Ordering::Relaxed);
                                        if done_tx_walker
                                            .send(PipelineMsg::Unchanged(prev.file_id))
                                            .is_err()
                                        {
                                            return ControlFlow::Break(());
                                        }
                                        return ControlFlow::Continue(());
                                    }
                                }
                            }

                            if let Some(limit) = max_files {
                                if queued_for_processing >= limit {
                                    truncated_ref.store(true, Ordering::Release);
                                    return ControlFlow::Break(());
                                }
                            }

                            queued_for_processing += 1;
                            discovered_ref.fetch_add(1, Ordering::Relaxed);
                            in_flight_ref.fetch_add(1, Ordering::AcqRel);
                            if work_tx.send(f).is_err() {
                                in_flight_ref.fetch_sub(1, Ordering::AcqRel);
                                return ControlFlow::Break(());
                            }
                        }
                    }
                    ControlFlow::Continue(())
                });
                walker_done_ref.store(true, Ordering::Release);
                drop(work_tx);
                drop(done_tx_walker);
            });

            // Stage 2: Device-concurrency-controlled Hash + EXIF workers
            let meta_ref = &meta_session;
            let bytes_ref = &bytes_counter;
            let pb_ref = &scan_pb;

            for _ in 0..workers {
                let rx_clone = Arc::clone(&work_rx);
                let tx_clone = done_tx.clone();
                let hash_algo = cfg.hash.algorithm;
                let partial_hash_enabled = cfg.hash.partial_hash_enabled;

                scope.spawn(move || loop {
                    if !gate_ref.wait_if_paused() {
                        break;
                    }
                    let next_file = {
                        let rx_guard = rx_clone.lock().unwrap_or_else(|e| e.into_inner());
                        rx_guard.recv().ok()
                    };
                    let Some(f) = next_file else {
                        break;
                    };
                    if !gate_ref.wait_if_paused() {
                        in_flight_ref.fetch_sub(1, Ordering::AcqRel);
                        break;
                    }

                    let msg = match hash_file(&f.abs_path, hash_algo, partial_hash_enabled) {
                        Ok(hash) => {
                            let is_sidecar = is_sidecar_extension(&f.ext);
                            let meta = if is_sidecar {
                                None
                            } else {
                                meta_ref.extract(&f.abs_path, &f.ext)
                            };
                            let file_role = if is_sidecar { FileRole::Sidecar } else { role };
                            let done_bytes =
                                bytes_ref.fetch_add(hash.bytes_read, Ordering::Relaxed)
                                    + hash.bytes_read;
                            pb_ref.inc(1);
                            let secs = proc_started.elapsed().as_secs_f64().max(0.001);
                            let mb_s = (done_bytes as f64 / 1_000_000.0) / secs;
                            pb_ref.set_message(format!(
                                "{}, {:.1} MB/s",
                                human_bytes(done_bytes),
                                mb_s
                            ));
                            let input = UpsertFileInput {
                                storage_id: storage.id.clone(),
                                rel_path: f.rel_path,
                                file_name: f.file_name,
                                file_stem: f.file_stem,
                                ext: f.ext,
                                byte_size: f.byte_size,
                                mtime_ns: f.mtime_ns,
                                ctime_ns: f.ctime_ns,
                                media_kind: f.media_kind,
                                format: f.format,
                                role: file_role,
                                hash_algo: hash.algorithm,
                                hash_hex: hash.hash_hex,
                                partial_hash: hash.partial_hash,
                                metadata: meta,
                            };
                            PipelineMsg::Processed(Box::new(input), hash.bytes_read)
                        }
                        Err(err) => PipelineMsg::ProcessError(err.to_string()),
                    };

                    let send_ok = tx_clone.send(msg).is_ok();
                    in_flight_ref.fetch_sub(1, Ordering::AcqRel);
                    if !send_ok {
                        break;
                    }
                });
            }

            // Drop parent handles so channels close cleanly if workers/consumer exit early
            drop(work_rx);
            drop(done_tx);

            // Stage 3: Batched SQLite writer, JSONL exporter, and HDD cooldown controller
            let mut unchanged_batch: Vec<i64> = Vec::with_capacity(batch_size.max(5_000));
            let unchanged_batch_cap = batch_size.max(5_000);
            let mut batch_inputs: Vec<UpsertFileInput> = Vec::with_capacity(batch_size);
            let mut processed_since_cooldown: usize = 0;
            let mut processed_total: u64 = 0;

            let drain_res: Result<()> = (|| {
                for msg in done_rx {
                    match msg {
                        PipelineMsg::DiscoveryError(err) => {
                            summary.error_count += 1;
                            warn!(storage_id = %storage.id, error = %err, "discovery error");
                        }
                        PipelineMsg::Unchanged(file_id) => {
                            summary.files_skipped += 1;
                            unchanged_batch.push(file_id);
                            if unchanged_batch.len() >= unchanged_batch_cap {
                                db.touch_unchanged_files(&unchanged_batch, scan_run_id)?;
                                unchanged_batch.clear();
                            }
                        }
                        PipelineMsg::ProcessError(err) => {
                            summary.error_count += 1;
                            processed_total += 1;
                            processed_since_cooldown += 1;
                            warn!(storage_id = %storage.id, error = %err, "file processing error");
                        }
                        PipelineMsg::Processed(input_box, bytes) => {
                            let input = *input_box;
                            summary.bytes_hashed += bytes;
                            if export_jsonl {
                                let rec = ScanManifestRecord {
                                    storage_id: input.storage_id.clone(),
                                    rel_path: input.rel_path.clone(),
                                    file_name: input.file_name.clone(),
                                    file_stem: input.file_stem.clone(),
                                    ext: input.ext.clone(),
                                    byte_size: input.byte_size,
                                    mtime_ns: input.mtime_ns,
                                    ctime_ns: input.ctime_ns,
                                    media_kind: input.media_kind,
                                    format: input.format.clone(),
                                    hash_algo: input.hash_algo,
                                    hash_hex: input.hash_hex.clone(),
                                    partial_hash: input.partial_hash.clone(),
                                    metadata: input.metadata.clone(),
                                };
                                println!("{}", serde_json::to_string(&rec)?);
                            }
                            batch_inputs.push(input);
                            processed_total += 1;
                            processed_since_cooldown += 1;

                            if batch_inputs.len() >= batch_size {
                                let (added, updated) =
                                    db.upsert_scanned_batch(&batch_inputs, scan_run_id)?;
                                summary.files_added += added;
                                summary.files_updated += updated;
                                batch_inputs.clear();
                            }
                        }
                    }

                    if cooldown_enabled && processed_since_cooldown >= cooldown_every {
                        if !batch_inputs.is_empty() {
                            let (added, updated) =
                                db.upsert_scanned_batch(&batch_inputs, scan_run_id)?;
                            summary.files_added += added;
                            summary.files_updated += updated;
                            batch_inputs.clear();
                        }
                        if !unchanged_batch.is_empty() {
                            db.touch_unchanged_files(&unchanged_batch, scan_run_id)?;
                            unchanged_batch.clear();
                        }
                        processed_since_cooldown = 0;

                        let more_pending = !walker_done_ref.load(Ordering::Acquire)
                            || in_flight_ref.load(Ordering::Acquire) > 0;
                        if more_pending {
                            gate_ref.pause();
                            pb_ref.set_message(format!(
                                "cooling down {}s ({} done)",
                                cooldown_secs,
                                human_bytes(summary.bytes_hashed)
                            ));
                            info!(
                                storage_id = %storage.id,
                                processed = processed_total,
                                cooldown_secs,
                                "batch committed; pausing pipeline for cooldown"
                            );
                            thread::sleep(Duration::from_secs(cooldown_secs));
                            gate_ref.resume();
                        }
                    }
                }

                if !unchanged_batch.is_empty() {
                    db.touch_unchanged_files(&unchanged_batch, scan_run_id)?;
                }
                if !batch_inputs.is_empty() {
                    let (added, updated) = db.upsert_scanned_batch(&batch_inputs, scan_run_id)?;
                    summary.files_added += added;
                    summary.files_updated += updated;
                }
                Ok(())
            })();

            if drain_res.is_err() {
                gate_ref.stop();
            }
            drain_res
        });

        scan_pb.finish_and_clear();
        pipeline_result?;
        summary.files_scanned = discovered_counter.load(Ordering::Relaxed);

        if !truncated_by_max_files.load(Ordering::Acquire) {
            summary.files_missing = db.mark_unseen_as_missing(&storage.id, scan_run_id)?;
        }
        let needs_post_sweep =
            mode == "full" || summary.files_added > 0 || summary.files_updated > 0;
        let (pair_report, sidecar_report) = if needs_post_sweep {
            let pr = db.pair_raw_jpeg_assets(&storage.id)?;
            let sr = db.link_sidecar_files(&storage.id)?;
            (pr, sr)
        } else {
            (Default::default(), Default::default())
        };
        summary.raw_jpeg_merged = pair_report.pairs_merged;
        db.finish_scan_run(&summary, None)?;

        info!(
            storage_id = %storage.id,
            elapsed_ms = started.elapsed().as_millis(),
            scanned = summary.files_scanned,
            added = summary.files_added,
            updated = summary.files_updated,
            skipped = summary.files_skipped,
            missing = summary.files_missing,
            raw_jpeg_merged = summary.raw_jpeg_merged,
            sidecars_linked = sidecar_report.linked,
            "scan completed"
        );
        summaries.push(summary);
    }

    if !export_jsonl {
        match format {
            OutputFormat::Json => println!("{}", serde_json::to_string_pretty(&summaries)?),
            OutputFormat::Jsonl => {
                for s in &summaries {
                    println!("{}", serde_json::to_string(s)?);
                }
            }
            OutputFormat::Text => {
                for s in &summaries {
                    println!(
                        "[{}] mode={} scanned={} added={} updated={} skipped={} missing={} paired={} hashed={} errors={}",
                        s.storage_id,
                        s.mode,
                        s.files_scanned,
                        s.files_added,
                        s.files_updated,
                        s.files_skipped,
                        s.files_missing,
                        s.raw_jpeg_merged,
                        human_bytes(s.bytes_hashed),
                        s.error_count,
                    );
                }
            }
        }
    }

    Ok(())
}

fn cmd_export_manifest(
    config_path: &Path,
    storage_id: &str,
    output_path: Option<&Path>,
    format: OutputFormat,
) -> Result<()> {
    let cfg = load_config_or_default(config_path)?;
    let db = Database::open(&cfg.general.db_path)?;

    let exported = match output_path {
        Some(path) => {
            let file = File::create(path)
                .with_context(|| format!("failed to create manifest file: {}", path.display()))?;
            let mut writer = BufWriter::new(file);
            let count = db.stream_storage_manifest(storage_id, |rec| {
                let line = serde_json::to_string(&rec).map_err(io::Error::other)?;
                writeln!(writer, "{line}")
            })?;
            writer.flush()?;
            count
        }
        None => {
            let stdout = io::stdout();
            let mut writer = BufWriter::new(stdout.lock());
            let _count = db.stream_storage_manifest(storage_id, |rec| {
                let line = serde_json::to_string(&rec).map_err(io::Error::other)?;
                writeln!(writer, "{line}")
            })?;
            writer.flush()?;
            return Ok(());
        }
    };

    #[derive(Serialize)]
    struct ExportSummary {
        storage_id: String,
        output_path: String,
        records_exported: u64,
    }

    let summary = ExportSummary {
        storage_id: storage_id.to_string(),
        output_path: output_path
            .map(|p| p.to_string_lossy().into_owned())
            .unwrap_or_default(),
        records_exported: exported,
    };

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&summary)?);
        }
        OutputFormat::Text => {
            println!(
                "Exported {} records for storage '{}' -> {}",
                summary.records_exported, summary.storage_id, summary.output_path
            );
        }
    }
    Ok(())
}

fn cmd_import_manifest(
    config_path: &Path,
    input_path: &Path,
    storage_override: Option<&str>,
    format: OutputFormat,
) -> Result<()> {
    const MAX_LINE_BYTES: usize = 4 * 1024 * 1024;

    let cfg = Config::load(config_path)
        .with_context(|| format!("failed to load config: {}", config_path.display()))?;
    let mut db = Database::open(&cfg.general.db_path)?;
    db.upsert_host(&cfg.host.id, &cfg.host.name, current_host_os())?;

    let file = File::open(input_path)
        .with_context(|| format!("failed to open manifest file: {}", input_path.display()))?;
    let mut reader = BufReader::new(file);
    let batch_size = cfg.performance.db_batch_size.max(1);

    let mut line = String::new();
    let mut line_no: u64 = 0;
    let mut total_read: u64 = 0;
    let mut total_added: u64 = 0;
    let mut total_updated: u64 = 0;
    let mut total_rejected: u64 = 0;
    let mut batches: std::collections::HashMap<String, Vec<UpsertFileInput>> =
        std::collections::HashMap::new();
    let mut scan_runs: std::collections::HashMap<String, i64> = std::collections::HashMap::new();

    loop {
        line.clear();
        let n = reader.read_line(&mut line)?;
        if n == 0 {
            break;
        }
        line_no += 1;
        if line.len() > MAX_LINE_BYTES {
            warn!(line_no, "manifest line exceeds size limit; rejecting");
            total_rejected += 1;
            continue;
        }
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }

        let mut rec: ScanManifestRecord = match serde_json::from_str(trimmed) {
            Ok(r) => r,
            Err(err) => {
                warn!(line_no, error = %err, "failed to parse manifest JSONL line");
                total_rejected += 1;
                continue;
            }
        };
        if let Some(override_id) = storage_override {
            rec.storage_id = override_id.to_string();
        }
        if let Err(reason) = rec.validate() {
            warn!(line_no, reason = %reason, "rejected invalid manifest record");
            total_rejected += 1;
            continue;
        }
        if let Some(meta) = rec.metadata.as_mut() {
            apply_lens_aliases(meta, &cfg.exif.lens_aliases);
        }

        let Some(storage_cfg) = cfg.storages.iter().find(|s| s.id == rec.storage_id) else {
            anyhow::bail!(
                "manifest references storage_id '{}' which is not configured in {} (use --storage to map it)",
                rec.storage_id,
                config_path.display()
            );
        };

        let run_id = if let Some(&rid) = scan_runs.get(&storage_cfg.id) {
            rid
        } else {
            let status = if storage_cfg.root.exists() {
                StorageStatus::Online
            } else {
                StorageStatus::Offline
            };
            db.upsert_storage(storage_cfg, &cfg.host.id, status)?;
            let rid = db.start_scan_run(&storage_cfg.id, "manifest-import")?;
            scan_runs.insert(storage_cfg.id.clone(), rid);
            rid
        };

        let file_role = if is_sidecar_extension(&rec.ext) {
            FileRole::Sidecar
        } else {
            storage_cfg.tier.default_file_role()
        };
        let input = UpsertFileInput {
            storage_id: storage_cfg.id.clone(),
            rel_path: rec.rel_path,
            file_name: rec.file_name,
            file_stem: rec.file_stem,
            ext: rec.ext,
            byte_size: rec.byte_size,
            mtime_ns: rec.mtime_ns,
            ctime_ns: rec.ctime_ns,
            media_kind: rec.media_kind,
            format: rec.format,
            role: file_role,
            hash_algo: rec.hash_algo,
            hash_hex: rec.hash_hex,
            partial_hash: rec.partial_hash,
            metadata: rec.metadata,
        };
        total_read += 1;

        let entry = batches.entry(storage_cfg.id.clone()).or_default();
        entry.push(input);
        if entry.len() >= batch_size {
            let to_flush = std::mem::take(entry);
            let (added, updated) = db.upsert_scanned_batch(&to_flush, run_id)?;
            total_added += added;
            total_updated += updated;
        }
    }

    let mut total_paired: u64 = 0;
    for (storage_id, items) in batches {
        let run_id = *scan_runs.get(&storage_id).unwrap();
        if !items.is_empty() {
            let (added, updated) = db.upsert_scanned_batch(&items, run_id)?;
            total_added += added;
            total_updated += updated;
        }
        let pair_rep = db.pair_raw_jpeg_assets(&storage_id)?;
        let _ = db.link_sidecar_files(&storage_id)?;
        total_paired += pair_rep.pairs_merged;

        let summary = ScanRunSummary {
            scan_run_id: run_id,
            storage_id: storage_id.clone(),
            mode: "manifest-import".to_string(),
            status: "completed".to_string(),
            files_scanned: total_read,
            files_added: total_added,
            files_updated: total_updated,
            raw_jpeg_merged: pair_rep.pairs_merged,
            error_count: total_rejected,
            ..Default::default()
        };
        db.finish_scan_run(&summary, None)?;
    }

    #[derive(Serialize)]
    struct ImportSummary {
        input_path: String,
        records_read: u64,
        files_added: u64,
        files_updated: u64,
        raw_jpeg_merged: u64,
        records_rejected: u64,
    }

    let summary = ImportSummary {
        input_path: input_path.to_string_lossy().into_owned(),
        records_read: total_read,
        files_added: total_added,
        files_updated: total_updated,
        raw_jpeg_merged: total_paired,
        records_rejected: total_rejected,
    };

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&summary)?);
        }
        OutputFormat::Text => {
            println!(
                "Imported manifest {}: read={} added={} updated={} paired={} rejected={}",
                summary.input_path,
                summary.records_read,
                summary.files_added,
                summary.files_updated,
                summary.raw_jpeg_merged,
                summary.records_rejected
            );
        }
    }
    Ok(())
}

fn cmd_normalize_lenses(config_path: &Path, dry_run: bool, format: OutputFormat) -> Result<()> {
    let cfg = load_config_or_default(config_path)?;
    let mut db = if dry_run {
        if !cfg.general.db_path.exists() {
            anyhow::bail!(
                "database does not exist (dry-run will not create it): {}",
                cfg.general.db_path.display()
            );
        }
        Database::open_read_only(&cfg.general.db_path)?
    } else {
        Database::open(&cfg.general.db_path)?
    };

    let report = db.reapply_lens_aliases(&cfg.exif.lens_aliases, dry_run)?;

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&report)?);
        }
        OutputFormat::Text => {
            let prefix = if report.dry_run { "[dry-run] " } else { "" };
            let verb = if report.dry_run {
                "would update"
            } else {
                "updated"
            };
            println!(
                "{prefix}Normalized lenses (aliases={}): {verb} assets={} contents={}",
                report.aliases_configured, report.assets_updated, report.contents_updated
            );
            for ch in &report.changes {
                println!(
                    "  - {:?} ({} -> {}): assets={} contents={}",
                    ch.raw_lens,
                    ch.previous_lens.as_deref().unwrap_or("(null)"),
                    ch.normalized_lens.as_deref().unwrap_or("(null)"),
                    ch.assets_affected,
                    ch.contents_affected
                );
            }
        }
    }
    Ok(())
}

fn cmd_link_derivatives(
    config_path: &Path,
    opts: DerivativeLinkOptions,
    limit: usize,
    format: OutputFormat,
) -> Result<()> {
    let cfg = load_config_or_default(config_path)?;
    if !cfg.general.db_path.exists() {
        anyhow::bail!("database does not exist: {}", cfg.general.db_path.display());
    }

    let report = if opts.dry_run {
        let db = Database::open_read_only(&cfg.general.db_path)?;
        db.plan_derivative_jpegs(&opts)?
    } else {
        let mut db = Database::open(&cfg.general.db_path)?;
        db.link_derivative_jpegs(&opts)?
    };

    match format {
        OutputFormat::Json => {
            println!("{}", serde_json::to_string_pretty(&report)?);
        }
        OutputFormat::Jsonl => {
            for m in &report.matches {
                println!("{}", serde_json::to_string(m)?);
            }
        }
        OutputFormat::Text => {
            let prefix = if report.dry_run { "[dry-run] " } else { "" };
            let verb = if report.dry_run {
                "would link"
            } else {
                "linked"
            };
            println!(
                "{prefix}Derivative JPEG linking: scanned_jpeg_assets={}  {verb}={} assets ({} files)  ambiguous_skipped={}",
                report.scanned_jpeg_assets,
                report.linked_assets,
                report.linked_files,
                report.ambiguous_skipped
            );
            if !report.by_reason.is_empty() {
                println!("\nBy Match Reason:");
                for (reason, cnt) in &report.by_reason {
                    println!("  - {:<28} {:>8}", reason, cnt);
                }
            }
            if !report.matches.is_empty() {
                let show_n = if limit == 0 {
                    report.matches.len()
                } else {
                    limit.min(report.matches.len())
                };
                println!(
                    "\nMatched Derivatives (showing {} of {}):",
                    show_n,
                    report.matches.len()
                );
                for m in report.matches.iter().take(show_n) {
                    println!(
                        "  - [{}] {}  ->  {}  (asset #{}, {})",
                        m.match_reason, m.derivative_path, m.target_path, m.target_asset_id, m.captured_at
                    );
                }
            }
            if !report.ambiguous_samples.is_empty() {
                println!(
                    "\nAmbiguous Skipped (Fail Closed, showing {} of {}):",
                    report.ambiguous_samples.len(),
                    report.ambiguous_skipped
                );
                for a in &report.ambiguous_samples {
                    println!(
                        "  - {} ({})  candidates=[{}]",
                        a.derivative_path,
                        a.captured_at,
                        a.candidate_paths.join(", ")
                    );
                }
            }
        }
    }
    Ok(())
}

