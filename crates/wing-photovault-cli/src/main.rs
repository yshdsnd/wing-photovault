#[derive(Debug, Clone, Copy, ValueEnum)]
enum OutputFormat {
    Text,
    Json,
    Jsonl,
}

#[derive(Debug, Parser)]
#[command(
    name = "wingpv",
    version,
    about = "WING PhotoVault CLI — fast, safe photo asset indexing and management"
)]
struct Cli {
    /// Path to TOML configuration file
    #[arg(long, global = true, default_value = "wing-photovault.toml")]
    config: PathBuf,

    /// Output format
    #[arg(long, global = true, value_enum, default_value_t = OutputFormat::Text)]
    format: OutputFormat,

    /// Enable verbose logging on stderr
    #[arg(short, long, global = true)]
    verbose: bool,

    /// Suppress informational logs on stderr
    #[arg(short, long, global = true)]
    quiet: bool,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Debug, Subcommand)]
enum Commands {
    /// Initialize SQLite database and register configured storages
    Init {
        /// Create a starter config file if it does not exist
        #[arg(long)]
        write_config: bool,
    },

    /// Non-destructively scan storages and update the index database
    Scan {
        /// Scan only a specific storage ID
        #[arg(long)]
        storage: Option<String>,

        /// Re-hash and re-extract metadata even for unchanged files
        #[arg(long)]
        full: bool,

        /// Stream scanned records as JSONL to stdout (for NAS remote scan workflow)
        #[arg(long)]
        export_jsonl: bool,

        /// Pause for cooldown after processing every N files (0 = disabled; great for NAS HDD thermals)
        #[arg(long, default_value_t = 0)]
        cooldown_every: usize,

        /// Cooldown sleep duration in seconds when --cooldown-every triggers
        #[arg(long, default_value_t = 0)]
        cooldown_secs: u64,

        /// Process at most N new/changed files in this run (skips missing-file marking when truncated)
        #[arg(long)]
        max_files: Option<usize>,
    },

    /// Export a storage's indexed files (hashes + EXIF) as a portable JSONL manifest
    ExportManifest {
        /// Storage ID to export
        #[arg(long)]
        storage: String,

        /// Output JSONL file path (prints to stdout if omitted)
        #[arg(short, long)]
        output: Option<PathBuf>,
    },

    /// Import a JSONL manifest generated by a remote/NAS local scan into this host's DB
    ImportManifest {
        /// Path to the JSONL manifest file
        input: PathBuf,

        /// Override storage_id in the manifest with a configured storage ID
        #[arg(long)]
        storage: Option<String>,
    },

    /// Re-apply [exif.lens_aliases] to existing DB records from lens_model_raw (no rescan required)
    NormalizeLenses {
        /// Preview changes without modifying the database
        #[arg(long)]
        dry_run: bool,
    },

    /// Show database and storage status
    Status,

    /// Show asset, content, format, camera, lens, and backup statistics
    Stats {
        /// Also show percentage share for backup coverage, formats, cameras, and lenses
        #[arg(long)]
        percent: bool,

        /// Include yearly asset counts, active shooting days, and top camera/lens per year
        #[arg(long)]
        by_year: bool,

        /// Include chronological camera and lens usage timeline (first..last capture dates)
        #[arg(long)]
        gear_history: bool,
    },

    /// Search indexed files
    Find {
        #[arg(long)]
        storage: Option<String>,
        #[arg(long = "ext-format")]
        ext_format: Option<String>,
        #[arg(long)]
        camera: Option<String>,
        #[arg(long)]
        lens: Option<String>,
        #[arg(long)]
        from: Option<String>,
        #[arg(long)]
        to: Option<String>,
        #[arg(long, default_value_t = 100)]
        limit: i64,
    },

    /// Benchmark scanning, BLAKE3 vs SHA-256 hashing, and EXIF extraction on a directory
    Benchmark {
        /// Target directory to benchmark (read-only)
        path: PathBuf,

        /// Maximum number of files to process
        #[arg(long, default_value_t = 500)]
        limit: usize,

        /// Also benchmark ExifTool CLI for comparison
        #[arg(long)]
        with_exiftool: bool,
    },
}

fn main() -> Result<()> {
    let cli = Cli::parse();
    init_logging(cli.verbose, cli.quiet);

    match cli.command {
        Commands::Init { write_config } => cmd_init(&cli.config, write_config, cli.format),
        Commands::Scan {
            storage,
            full,
            export_jsonl,
            cooldown_every,
            cooldown_secs,
            max_files,
        } => cmd_scan(
            &cli.config,
            ScanOpts {
                storage_filter: storage.as_deref(),
                full,
                export_jsonl,
                cooldown_every,
                cooldown_secs,
                max_files,
                quiet: cli.quiet,
                format: cli.format,
            },
        ),
        Commands::ExportManifest { storage, output } => {
            cmd_export_manifest(&cli.config, &storage, output.as_deref(), cli.format)
        }
        Commands::ImportManifest { input, storage } => {
            cmd_import_manifest(&cli.config, &input, storage.as_deref(), cli.format)
        }
        Commands::NormalizeLenses { dry_run } => {
            cmd_normalize_lenses(&cli.config, dry_run, cli.format)
        }
        Commands::Status => cmd_status(&cli.config, cli.format),
        Commands::Stats {
            percent,
            by_year,
            gear_history,
        } => cmd_stats(&cli.config, percent, by_year, gear_history, cli.format),
        Commands::Find {
            storage,
            ext_format,
            camera,
            lens,
            from,
            to,
            limit,
        } => cmd_find(
            &cli.config,
            FindFilter {
                storage_id: storage,
                format: ext_format,
                camera,
                lens,
                from_date: from,
                to_date: to,
                limit: Some(limit),
            },
            cli.format,
        ),
        Commands::Benchmark {
            path,
            limit,
            with_exiftool,
        } => cmd_benchmark(&cli.config, &path, limit, with_exiftool, cli.format),
    }
}

fn init_logging(verbose: bool, quiet: bool) {
    let level = if quiet {
        "error"
    } else if verbose {
        "debug"
    } else {
        "info"
    };
    let filter = EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new(level));
    tracing_subscriber::fmt()
        .with_env_filter(filter)
        .with_writer(std::io::stderr)
        .init();
}

fn load_config_or_default(path: &Path) -> Result<Config> {
    if path.exists() {
        Config::load(path).with_context(|| format!("failed to load config: {}", path.display()))
    } else {
        Ok(Config {
            host: Default::default(),
            general: Default::default(),
            scan: Default::default(),
            hash: Default::default(),
            performance: Default::default(),
            exif: Default::default(),
            storages: Vec::new(),
        })
    }
}

fn cmd_init(config_path: &Path, write_config: bool, format: OutputFormat) -> Result<()> {
    if write_config && !config_path.exists() {
        let example = include_str!("../../../config.example.toml");
        std::fs::write(config_path, example)
            .with_context(|| format!("failed to write {}", config_path.display()))?;
        info!(path = %config_path.display(), "wrote starter config");
    }

    let cfg = load_config_or_default(config_path)?;
    let db = Database::open(&cfg.general.db_path)
        .with_context(|| format!("failed to open DB: {}", cfg.general.db_path.display()))?;

    db.upsert_host(&cfg.host.id, &cfg.host.name, current_host_os())?;

    for s in &cfg.storages {
        let status = if s.root.exists() {
            StorageStatus::Online
        } else {
            StorageStatus::Offline
        };
        db.upsert_storage(s, &cfg.host.id, status)?;
    }

    #[derive(Serialize)]
    struct InitResult {
        db_path: String,
        storages_registered: usize,
    }

    let res = InitResult {
        db_path: cfg.general.db_path.to_string_lossy().into_owned(),
        storages_registered: cfg.storages.len(),
    };

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&res)?);
        }
        OutputFormat::Text => {
            println!("Initialized database: {}", res.db_path);
            println!("Registered storages: {}", res.storages_registered);
        }
    }
    Ok(())
}

struct ScanOpts<'a> {
    storage_filter: Option<&'a str>,
    full: bool,
    export_jsonl: bool,
    cooldown_every: usize,
    cooldown_secs: u64,
    max_files: Option<usize>,
    quiet: bool,
    format: OutputFormat,
}

fn cmd_scan(config_path: &Path, opts: ScanOpts<'_>) -> Result<()> {
    let ScanOpts {
        storage_filter,
        full,
        export_jsonl,
        cooldown_every,
        cooldown_secs,
        max_files,
        quiet,
        format,
    } = opts;
    let cfg = Config::load(config_path)
        .with_context(|| format!("failed to load config: {}", config_path.display()))?;
    let mut db = Database::open(&cfg.general.db_path)?;
    db.upsert_host(&cfg.host.id, &cfg.host.name, current_host_os())?;
    let allowed_exts = cfg.normalized_extensions();

    let targets: Vec<&StorageConfig> = cfg
        .storages
        .iter()
        .filter(|s| storage_filter.is_none_or(|id| s.id == id))
        .collect();

    if targets.is_empty() {
        anyhow::bail!("no matching storages found in {}", config_path.display());
    }

    let mut summaries = Vec::new();
    let mode = if full || !cfg.scan.incremental {
        "full"
    } else {
        "incremental"
    };

    for storage in targets {
        if !storage.root.exists() {
            warn!(
                storage_id = %storage.id,
                root = %storage.root.display(),
                "storage root is offline/inaccessible; skipping without marking files missing"
            );
            db.upsert_storage(storage, &cfg.host.id, StorageStatus::Offline)?;
            continue;
        }

        db.upsert_storage(storage, &cfg.host.id, StorageStatus::Online)?;
        let scan_run_id = db.start_scan_run(&storage.id, mode)?;
        let started = Instant::now();

        let existing = db.load_storage_file_index(&storage.id)?;

        let discover_pb = if quiet {
            ProgressBar::hidden()
        } else {
            let pb = ProgressBar::with_draw_target(None, ProgressDrawTarget::stderr());
            pb.set_style(
                ProgressStyle::with_template("{spinner:.cyan} [{prefix}] Discovering files... {elapsed_precise}")
                    .unwrap(),
            );
            pb.set_prefix(storage.id.clone());
            pb.enable_steady_tick(Duration::from_millis(120));
            pb
        };
        let discovery = discover_storage_files(storage, &allowed_exts, cfg.scan.follow_symlinks);
        discover_pb.finish_and_clear();
        let mut summary = ScanRunSummary {
            scan_run_id,
            storage_id: storage.id.clone(),
            mode: mode.to_string(),
            status: "completed".to_string(),
            files_scanned: discovery.files.len() as u64,
            error_count: discovery.errors.len() as u64,
            ..Default::default()
        };

        for err in &discovery.errors {
            warn!(storage_id = %storage.id, error = %err, "discovery error");
        }

        let mut unchanged_ids: Vec<i64> = Vec::new();
        let mut to_process: Vec<DiscoveredFile> = Vec::new();

        for f in discovery.files {
            if mode == "incremental" {
                if let Some(prev) = existing.get(&f.rel_path) {
                    if prev.byte_size == f.byte_size
                        && prev.mtime_ns == f.mtime_ns
                        && prev.content_id.is_some()
                    {
                        unchanged_ids.push(prev.file_id);
                        continue;
                    }
                }
            }
            to_process.push(f);
        }

        summary.files_skipped = unchanged_ids.len() as u64;
        db.touch_unchanged_files(&unchanged_ids, scan_run_id)?;

        let mut truncated_by_max_files = false;
        if let Some(limit) = max_files {
            if to_process.len() > limit {
                to_process.truncate(limit);
                truncated_by_max_files = true;
            }
        }

        let workers = cfg.performance.workers_for(storage.media);
        let pool = rayon::ThreadPoolBuilder::new()
            .num_threads(workers)
            .build()
            .context("failed to build worker pool")?;

        let cooldown_enabled = cooldown_every > 0 && cooldown_secs > 0;
        let base_batch = cfg.performance.db_batch_size.max(1);
        let batch_size = if cooldown_enabled {
            base_batch.min(cooldown_every)
        } else {
            base_batch
        };
        let role = storage.tier.default_file_role();

        let total_to_process = to_process.len() as u64;
        let scan_pb = if quiet || total_to_process == 0 {
            ProgressBar::hidden()
        } else {
            let pb = ProgressBar::with_draw_target(
                Some(total_to_process),
                ProgressDrawTarget::stderr(),
            );
            pb.set_style(
                ProgressStyle::with_template(
                    "[{prefix}] [{bar:30.cyan/blue}] {pos}/{len} files ({msg}) ETA {eta}",
                )
                .unwrap()
                .progress_chars("=>-"),
            );
            pb.set_prefix(storage.id.clone());
            pb.set_message("0 B");
            pb
        };
        let bytes_counter = AtomicU64::new(0);
        let proc_started = Instant::now();
        let meta_session = MetadataSession::new(cfg.exif.clone());
        let mut processed_since_cooldown: usize = 0;
        let mut processed_total: usize = 0;

        for chunk in to_process.chunks(batch_size) {
            let results: Vec<Result<(UpsertFileInput, u64)>> = pool.install(|| {
                chunk
                    .par_iter()
                    .map(|f| {
                        let hash = hash_file(
                            &f.abs_path,
                            cfg.hash.algorithm,
                            cfg.hash.partial_hash_enabled,
                        )?;
                        let meta = meta_session.extract(&f.abs_path, &f.ext);
                        let done_bytes =
                            bytes_counter.fetch_add(hash.bytes_read, Ordering::Relaxed)
                                + hash.bytes_read;
                        scan_pb.inc(1);
                        let secs = proc_started.elapsed().as_secs_f64().max(0.001);
                        let mb_s = (done_bytes as f64 / 1_000_000.0) / secs;
                        scan_pb.set_message(format!(
                            "{}, {:.1} MB/s",
                            human_bytes(done_bytes),
                            mb_s
                        ));
                        let input = UpsertFileInput {
                            storage_id: storage.id.clone(),
                            rel_path: f.rel_path.clone(),
                            file_name: f.file_name.clone(),
                            file_stem: f.file_stem.clone(),
                            ext: f.ext.clone(),
                            byte_size: f.byte_size,
                            mtime_ns: f.mtime_ns,
                            ctime_ns: f.ctime_ns,
                            media_kind: f.media_kind,
                            format: f.format.clone(),
                            role,
                            hash_algo: hash.algorithm,
                            hash_hex: hash.hash_hex,
                            partial_hash: hash.partial_hash,
                            metadata: meta,
                        };
                        Ok((input, hash.bytes_read))
                    })
                    .collect()
            });

            let mut batch_inputs = Vec::with_capacity(results.len());
            for r in results {
                match r {
                    Ok((input, bytes)) => {
                        summary.bytes_hashed += bytes;
                        if export_jsonl {
                            let rec = ScanManifestRecord {
                                storage_id: input.storage_id.clone(),
                                rel_path: input.rel_path.clone(),
                                file_name: input.file_name.clone(),
                                file_stem: input.file_stem.clone(),
                                ext: input.ext.clone(),
                                byte_size: input.byte_size,
                                mtime_ns: input.mtime_ns,
                                ctime_ns: input.ctime_ns,
                                media_kind: input.media_kind,
                                format: input.format.clone(),
                                hash_algo: input.hash_algo,
                                hash_hex: input.hash_hex.clone(),
                                partial_hash: input.partial_hash.clone(),
                                metadata: input.metadata.clone(),
                            };
                            println!("{}", serde_json::to_string(&rec)?);
                        }
                        batch_inputs.push(input);
                    }
                    Err(err) => {
                        summary.error_count += 1;
                        warn!(storage_id = %storage.id, error = %err, "file processing error");
                    }
                }
            }

            let (added, updated) = db.upsert_scanned_batch(&batch_inputs, scan_run_id)?;
            summary.files_added += added;
            summary.files_updated += updated;
            processed_total += chunk.len();
            processed_since_cooldown += chunk.len();

            if cooldown_enabled
                && processed_since_cooldown >= cooldown_every
                && processed_total < to_process.len()
            {
                processed_since_cooldown = 0;
                scan_pb.set_message(format!(
                    "cooling down {}s ({} done)",
                    cooldown_secs,
                    human_bytes(summary.bytes_hashed)
                ));
                info!(
                    storage_id = %storage.id,
                    processed = processed_total,
                    total = to_process.len(),
                    cooldown_secs,
                    "batch committed; pausing for cooldown"
                );
                thread::sleep(Duration::from_secs(cooldown_secs));
            }
        }

        scan_pb.finish_and_clear();

        if !truncated_by_max_files {
            summary.files_missing = db.mark_unseen_as_missing(&storage.id, scan_run_id)?;
        }
        let pair_report = db.pair_raw_jpeg_assets(&storage.id)?;
        summary.raw_jpeg_merged = pair_report.pairs_merged;
        db.finish_scan_run(&summary, None)?;

        info!(
            storage_id = %storage.id,
            elapsed_ms = started.elapsed().as_millis(),
            scanned = summary.files_scanned,
            added = summary.files_added,
            updated = summary.files_updated,
            skipped = summary.files_skipped,
            missing = summary.files_missing,
            raw_jpeg_merged = summary.raw_jpeg_merged,
            "scan completed"
        );
        summaries.push(summary);
    }

    if !export_jsonl {
        match format {
            OutputFormat::Json => println!("{}", serde_json::to_string_pretty(&summaries)?),
            OutputFormat::Jsonl => {
                for s in &summaries {
                    println!("{}", serde_json::to_string(s)?);
                }
            }
            OutputFormat::Text => {
                for s in &summaries {
                    println!(
                        "[{}] mode={} scanned={} added={} updated={} skipped={} missing={} paired={} hashed={} errors={}",
                        s.storage_id,
                        s.mode,
                        s.files_scanned,
                        s.files_added,
                        s.files_updated,
                        s.files_skipped,
                        s.files_missing,
                        s.raw_jpeg_merged,
                        human_bytes(s.bytes_hashed),
                        s.error_count,
                    );
                }
            }
        }
    }

    Ok(())
}

fn cmd_export_manifest(
    config_path: &Path,
    storage_id: &str,
    output_path: Option<&Path>,
    format: OutputFormat,
) -> Result<()> {
    let cfg = load_config_or_default(config_path)?;
    let db = Database::open(&cfg.general.db_path)?;

    let exported = match output_path {
        Some(path) => {
            let file = File::create(path)
                .with_context(|| format!("failed to create manifest file: {}", path.display()))?;
            let mut writer = BufWriter::new(file);
            let count = db.stream_storage_manifest(storage_id, |rec| {
                let line = serde_json::to_string(&rec).map_err(io::Error::other)?;
                writeln!(writer, "{line}")
            })?;
            writer.flush()?;
            count
        }
        None => {
            let stdout = io::stdout();
            let mut writer = BufWriter::new(stdout.lock());
            let _count = db.stream_storage_manifest(storage_id, |rec| {
                let line = serde_json::to_string(&rec).map_err(io::Error::other)?;
                writeln!(writer, "{line}")
            })?;
            writer.flush()?;
            return Ok(());
        }
    };

    #[derive(Serialize)]
    struct ExportSummary {
        storage_id: String,
        output_path: String,
        records_exported: u64,
    }

    let summary = ExportSummary {
        storage_id: storage_id.to_string(),
        output_path: output_path
            .map(|p| p.to_string_lossy().into_owned())
            .unwrap_or_default(),
        records_exported: exported,
    };

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&summary)?);
        }
        OutputFormat::Text => {
            println!(
                "Exported {} records for storage '{}' -> {}",
                summary.records_exported, summary.storage_id, summary.output_path
            );
        }
    }
    Ok(())
}

fn cmd_import_manifest(
    config_path: &Path,
    input_path: &Path,
    storage_override: Option<&str>,
    format: OutputFormat,
) -> Result<()> {
    const MAX_LINE_BYTES: usize = 4 * 1024 * 1024;

    let cfg = Config::load(config_path)
        .with_context(|| format!("failed to load config: {}", config_path.display()))?;
    let mut db = Database::open(&cfg.general.db_path)?;
    db.upsert_host(&cfg.host.id, &cfg.host.name, current_host_os())?;

    let file = File::open(input_path)
        .with_context(|| format!("failed to open manifest file: {}", input_path.display()))?;
    let mut reader = BufReader::new(file);
    let batch_size = cfg.performance.db_batch_size.max(1);

    let mut line = String::new();
    let mut line_no: u64 = 0;
    let mut total_read: u64 = 0;
    let mut total_added: u64 = 0;
    let mut total_updated: u64 = 0;
    let mut total_rejected: u64 = 0;
    let mut batches: std::collections::HashMap<String, Vec<UpsertFileInput>> =
        std::collections::HashMap::new();
    let mut scan_runs: std::collections::HashMap<String, i64> = std::collections::HashMap::new();

    loop {
        line.clear();
        let n = reader.read_line(&mut line)?;
        if n == 0 {
            break;
        }
        line_no += 1;
        if line.len() > MAX_LINE_BYTES {
            warn!(line_no, "manifest line exceeds size limit; rejecting");
            total_rejected += 1;
            continue;
        }
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }

        let mut rec: ScanManifestRecord = match serde_json::from_str(trimmed) {
            Ok(r) => r,
            Err(err) => {
                warn!(line_no, error = %err, "failed to parse manifest JSONL line");
                total_rejected += 1;
                continue;
            }
        };
        if let Some(override_id) = storage_override {
            rec.storage_id = override_id.to_string();
        }
        if let Err(reason) = rec.validate() {
            warn!(line_no, reason = %reason, "rejected invalid manifest record");
            total_rejected += 1;
            continue;
        }
        if let Some(meta) = rec.metadata.as_mut() {
            apply_lens_aliases(meta, &cfg.exif.lens_aliases);
        }

        let Some(storage_cfg) = cfg.storages.iter().find(|s| s.id == rec.storage_id) else {
            anyhow::bail!(
                "manifest references storage_id '{}' which is not configured in {} (use --storage to map it)",
                rec.storage_id,
                config_path.display()
            );
        };

        let run_id = if let Some(&rid) = scan_runs.get(&storage_cfg.id) {
            rid
        } else {
            let status = if storage_cfg.root.exists() {
                StorageStatus::Online
            } else {
                StorageStatus::Offline
            };
            db.upsert_storage(storage_cfg, &cfg.host.id, status)?;
            let rid = db.start_scan_run(&storage_cfg.id, "manifest-import")?;
            scan_runs.insert(storage_cfg.id.clone(), rid);
            rid
        };

        let input = UpsertFileInput {
            storage_id: storage_cfg.id.clone(),
            rel_path: rec.rel_path,
            file_name: rec.file_name,
            file_stem: rec.file_stem,
            ext: rec.ext,
            byte_size: rec.byte_size,
            mtime_ns: rec.mtime_ns,
            ctime_ns: rec.ctime_ns,
            media_kind: rec.media_kind,
            format: rec.format,
            role: storage_cfg.tier.default_file_role(),
            hash_algo: rec.hash_algo,
            hash_hex: rec.hash_hex,
            partial_hash: rec.partial_hash,
            metadata: rec.metadata,
        };
        total_read += 1;

        let entry = batches.entry(storage_cfg.id.clone()).or_default();
        entry.push(input);
        if entry.len() >= batch_size {
            let to_flush = std::mem::take(entry);
            let (added, updated) = db.upsert_scanned_batch(&to_flush, run_id)?;
            total_added += added;
            total_updated += updated;
        }
    }

    let mut total_paired: u64 = 0;
    for (storage_id, items) in batches {
        let run_id = *scan_runs.get(&storage_id).unwrap();
        if !items.is_empty() {
            let (added, updated) = db.upsert_scanned_batch(&items, run_id)?;
            total_added += added;
            total_updated += updated;
        }
        let pair_rep = db.pair_raw_jpeg_assets(&storage_id)?;
        total_paired += pair_rep.pairs_merged;

        let summary = ScanRunSummary {
            scan_run_id: run_id,
            storage_id: storage_id.clone(),
            mode: "manifest-import".to_string(),
            status: "completed".to_string(),
            files_scanned: total_read,
            files_added: total_added,
            files_updated: total_updated,
            raw_jpeg_merged: pair_rep.pairs_merged,
            error_count: total_rejected,
            ..Default::default()
        };
        db.finish_scan_run(&summary, None)?;
    }

    #[derive(Serialize)]
    struct ImportSummary {
        input_path: String,
        records_read: u64,
        files_added: u64,
        files_updated: u64,
        raw_jpeg_merged: u64,
        records_rejected: u64,
    }

    let summary = ImportSummary {
        input_path: input_path.to_string_lossy().into_owned(),
        records_read: total_read,
        files_added: total_added,
        files_updated: total_updated,
        raw_jpeg_merged: total_paired,
        records_rejected: total_rejected,
    };

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&summary)?);
        }
        OutputFormat::Text => {
            println!(
                "Imported manifest {}: read={} added={} updated={} paired={} rejected={}",
                summary.input_path,
                summary.records_read,
                summary.files_added,
                summary.files_updated,
                summary.raw_jpeg_merged,
                summary.records_rejected
            );
        }
    }
    Ok(())
}

fn cmd_normalize_lenses(config_path: &Path, dry_run: bool, format: OutputFormat) -> Result<()> {
    let cfg = load_config_or_default(config_path)?;
    let mut db = if dry_run {
        if !cfg.general.db_path.exists() {
            anyhow::bail!(
                "database does not exist (dry-run will not create it): {}",
                cfg.general.db_path.display()
            );
        }
        Database::open_read_only(&cfg.general.db_path)?
    } else {
        Database::open(&cfg.general.db_path)?
    };

    let report = db.reapply_lens_aliases(&cfg.exif.lens_aliases, dry_run)?;

    match format {
        OutputFormat::Json | OutputFormat::Jsonl => {
            println!("{}", serde_json::to_string_pretty(&report)?);
        }
        OutputFormat::Text => {
            let prefix = if report.dry_run { "[dry-run] " } else { "" };
            let verb = if report.dry_run {
                "would update"
            } else {
                "updated"
            };
            println!(
                "{prefix}Normalized lenses (aliases={}): {verb} assets={} contents={}",
                report.aliases_configured, report.assets_updated, report.contents_updated
            );
            for ch in &report.changes {
                println!(
                    "  - {:?} ({} -> {}): assets={} contents={}",
                    ch.raw_lens,
                    ch.previous_lens.as_deref().unwrap_or("(null)"),
                    ch.normalized_lens.as_deref().unwrap_or("(null)"),
                    ch.assets_affected,
                    ch.contents_affected
                );
            }
        }
    }
    Ok(())
}

