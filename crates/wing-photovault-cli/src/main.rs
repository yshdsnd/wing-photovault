#[derive(Debug, Clone, Copy, ValueEnum)]
enum OutputFormat {
    Text,
    Json,
    Jsonl,
}

#[derive(Debug, Parser)]
#[command(
    name = "wingpv",
    version,
    about = "WING PhotoVault CLI — fast, safe photo asset indexing and management"
)]
struct Cli {
    /// Path to TOML configuration file
    #[arg(long, global = true, default_value = "wing-photovault.toml")]
    config: PathBuf,

    /// Output format
    #[arg(long, global = true, value_enum, default_value_t = OutputFormat::Text)]
    format: OutputFormat,

    /// Enable verbose logging on stderr
    #[arg(short, long, global = true)]
    verbose: bool,

    /// Suppress informational logs on stderr
    #[arg(short, long, global = true)]
    quiet: bool,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Debug, Subcommand)]
enum Commands {
    /// Initialize SQLite database and register configured storages
    Init {
        /// Create a starter config file if it does not exist
        #[arg(long)]
        write_config: bool,
    },

    /// Non-destructively scan storages and update the index database
    Scan {
        /// Scan only a specific storage ID
        #[arg(long)]
        storage: Option<String>,

        /// Re-hash and re-extract metadata even for unchanged files
        #[arg(long)]
        full: bool,

        /// Stream scanned records as JSONL to stdout (for NAS remote scan workflow)
        #[arg(long)]
        export_jsonl: bool,

        /// Pause for cooldown after processing every N files (0 = disabled; great for NAS HDD thermals)
        #[arg(long, default_value_t = 0)]
        cooldown_every: usize,

        /// Cooldown sleep duration in seconds when --cooldown-every triggers
        #[arg(long, default_value_t = 0)]
        cooldown_secs: u64,

        /// Process at most N new/changed files in this run (skips missing-file marking when truncated)
        #[arg(long)]
        max_files: Option<usize>,
    },

    /// Export a storage's indexed files (hashes + EXIF) as a portable JSONL manifest
    ExportManifest {
        /// Storage ID to export
        #[arg(long)]
        storage: String,

        /// Output JSONL file path (prints to stdout if omitted)
        #[arg(short, long)]
        output: Option<PathBuf>,
    },

    /// Import a JSONL manifest generated by a remote/NAS local scan into this host's DB
    ImportManifest {
        /// Path to the JSONL manifest file
        input: PathBuf,

        /// Override storage_id in the manifest with a configured storage ID
        #[arg(long)]
        storage: Option<String>,
    },

    /// Re-apply [exif.lens_aliases] to existing DB records from lens_model_raw (no rescan required)
    NormalizeLenses {
        /// Preview changes without modifying the database
        #[arg(long)]
        dry_run: bool,
    },

    /// Link retouched/exported JPEG files to their original logical Asset using capture timestamp (+ subsec/stem/EXIF guards)
    LinkDerivatives {
        /// Preview derivative links without modifying the database
        #[arg(long)]
        dry_run: bool,

        /// Restrict candidate derivative JPEGs to a single storage ID (targets still searched across all storages)
        #[arg(long)]
        storage: Option<String>,

        /// Only link to RAW-backed original Assets (skip JPEG-only -> JPEG-only derivatives)
        #[arg(long)]
        raw_only: bool,

        /// Maximum number of sample match rows to print in text output (0 = all)
        #[arg(long, default_value_t = 30)]
        limit: usize,
    },

    /// Show database and storage status
    Status,

    /// Show asset, content, format, camera, lens, focal-length, and backup statistics
    Stats(Box<StatsArgs>),

    /// Detect exact duplicate files (read-only; never flags intentional cross-tier backups)
    Duplicates {
        /// Restrict duplicate search to a single storage ID
        #[arg(long)]
        storage: Option<String>,

        /// Also include within-storage duplicates inside read-only/backup storages (marked protected)
        #[arg(long)]
        include_backups: bool,

        /// Also include sidecar files (.xmp, .thm)
        #[arg(long)]
        include_sidecars: bool,

        /// Minimum single-file size in bytes (e.g. 1048576 for 1 MB)
        #[arg(long, default_value_t = 0)]
        min_bytes: u64,

        /// Maximum number of duplicate groups to show (0 = unlimited)
        #[arg(long, default_value_t = 50)]
        limit: usize,
    },

    /// Search indexed files (and optionally perform verified safe copy to a working directory)
    Find(Box<FindArgs>),

    /// Verify on-disk file hashes against DB records to detect silent bit-rot or missing files (read-only on disk)
    Verify {
        /// Restrict verification to a single storage ID (default: all online configured storages)
        #[arg(long)]
        storage: Option<String>,

        /// Only verify files never verified or last verified more than N days ago
        #[arg(long)]
        older_than_days: Option<u64>,

        /// Maximum number of files to verify per storage (0 = unlimited)
        #[arg(long, default_value_t = 0)]
        limit: usize,

        /// Pause for `--cooldown-secs` after every N verified files (HDD thermal protection)
        #[arg(long, default_value_t = 0)]
        cooldown_every: usize,

        /// Cooldown pause duration in seconds when `--cooldown-every` is enabled
        #[arg(long, default_value_t = 0)]
        cooldown_secs: u64,

        /// Compute and check hashes without updating DB timestamps, presence, or operation journal
        #[arg(long)]
        dry_run: bool,
    },

    /// Inspect the Phase 2 operation journal (audit log and crash-recovery state)
    Journal {
        /// Filter by operation type (copy, ingest, move, quarantine, restore, verify)
        #[arg(long)]
        op_type: Option<String>,

        /// Filter by state (planned, copied, verified, committed, failed, rolled_back)
        #[arg(long)]
        state: Option<String>,

        /// Show only incomplete entries (not committed, failed, or rolled_back)
        #[arg(long)]
        incomplete: bool,

        /// Maximum number of entries to display (0 = unlimited)
        #[arg(long, default_value_t = 50)]
        limit: usize,
    },

    /// Safely ingest new photos/videos from temporary removable media (SD / CFexpress card) into a managed storage (card is read-only and never registered in storages)
    Ingest {
        /// Source directory on the memory card (read-only; never mutated or deleted)
        source: PathBuf,

        /// Destination managed storage ID configured in the TOML file (e.g. ssd_hot_g)
        #[arg(long)]
        to: String,

        /// Folder layout under destination root: YYYY/YYYY_MM_DD (default), YYYY/MM/YYYY_MM_DD, YYYY-MM-DD, or flat
        #[arg(long, default_value = "YYYY/YYYY_MM_DD")]
        date_layout: String,

        /// Optional safe folder suffix appended to the date folder (e.g. haneda -> 2026/2026_11_28_haneda/)
        #[arg(long)]
        subdir: Option<String>,

        /// Also ingest sidecar files (.xmp, .thm) from the card
        #[arg(long)]
        include_sidecars: bool,

        /// Preview ingest plan without creating directories, copying files, or modifying DB/journal
        #[arg(long)]
        dry_run: bool,
    },

    /// Benchmark scanning/hashing/EXIF on a directory, or SQLite query/aggregation scale via `--db-scale <N>`
    Benchmark {
        /// Target directory to benchmark (read-only)
        #[arg(conflicts_with = "db_scale")]
        path: Option<PathBuf>,

        /// Maximum number of files to process (directory benchmark mode)
        #[arg(long, default_value_t = 500)]
        limit: usize,

        /// Also benchmark ExifTool CLI for comparison (directory benchmark mode)
        #[arg(long)]
        with_exiftool: bool,

        /// Benchmark DB query/aggregation performance on a temporary synthetic DB with N files (e.g. 100000)
        #[arg(long)]
        db_scale: Option<usize>,
    },
}

